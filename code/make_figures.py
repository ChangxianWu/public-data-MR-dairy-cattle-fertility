# ---------- Figure 6: mammary eQTL proximity ----------
print('Figure 6: mammary eQTL proximity')
try:
    ev = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'supplementary', 'mammary_lead250k_eQTL_2026-09-16.json'), encoding='utf-8'))
    by = collections.defaultdict(list)
    for r in ev: by[(r['Trait'], r['GWAS_lead'])].append(r)
    labels = []; counts = []; bestp = []
    for k, v in sorted(by.items(), key=lambda x: -len(x[1])):
        labels.append(f"{k[0][:14]}\n{k[1]}")
        counts.append(len(v))
        bestp.append(min(r['eQTL_P'] for r in v))
    fig, ax = plt.subplots(figsize=(6.4, 3.6))
    yy = np.arange(len(labels))
    ax.barh(yy, counts, color=BLUE, height=0.6)
    for yi, c, p in zip(yy, counts, bestp):
        ax.text(c + 40, yi, f'n={c}; best eQTL P={p:.1e}', va='center', fontsize=7)
    ax.set_yticks(yy); ax.set_yticklabels(labels, fontsize=7)
    ax.invert_yaxis()
    ax.set_xlabel(f'Mammary cis-eQTL (P<1e-5) within ±250kb of MR lead')
    ax.set_title('CattleGTEx Mammary_Gland (N=830): eQTL density near MR leads', fontsize=9)
    ax.spines[['top', 'right']].set_visible(False)
    save(fig, 'Fig6_mammary_eQTL_proximity')
except Exception as e:
    print('  Fig6 skip:', e)


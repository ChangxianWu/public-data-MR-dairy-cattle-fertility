"""Manuscript Figures 1-7 (matplotlib; 300 dpi PNG + PDF).
Inputs: the result tables regenerated by run_mr_main.py (results/). """
import sys, os, csv, math, collections
sys.stdout.reconfigure(encoding='utf-8', errors='replace')
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import norm
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'results')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'figures')
os.makedirs(OUT, exist_ok=True)
plt.rcParams.update({'font.size': 9, 'axes.linewidth': 0.8, 'figure.dpi': 300,
                     'savefig.dpi': 300, 'font.family': 'DejaVu Sans'})
GREEN = '#198754'; GREY = '#888888'; RED = '#c0392b'; BLUE = '#2c5f8a'

def save(fig, name):
    fig.savefig(os.path.join(OUT, name + '.png'), bbox_inches='tight')
    fig.savefig(os.path.join(OUT, name + '.pdf'), bbox_inches='tight')
    plt.close(fig)
    print('  saved', name)

def rd(name):
    return list(csv.DictReader(open(os.path.join(ROOT, name), encoding='utf-8'), delimiter='\t'))

# ---------- Figure 1: IV construction funnel ----------
print('Figure 1: IV construction funnel')
fig, ax = plt.subplots(figsize=(6.2, 3.6))
stages = ['S8 high-confidence\nsignals', 'Signals in 24 exposure\ntraits', 'Representative SNP\nselected (lead/proxy)',
          'Allele-strand\nverifiable leads', 'IVs after orientation\n(253; 53 lead + 200 proxy)']
vals = [792, 643, 253, 253, 253]
notes = ['', 'in 24 exposure traits', 'lead 53 / proxy 200', '570 leads verifiable genome-wide',
         'strand: 108 same / 145 flipped\n(per-IV audit table)']
y = np.arange(len(stages))[::-1]
ax.barh(y, vals, color=[GREEN, '#4c9e7e', '#7ab8a1', '#a5d0c0', GREY], height=0.62)
for yi, v, nt in zip(y, vals, notes):
    ax.text(v + 12, yi, f'{v}', va='center', fontsize=9, fontweight='bold')
    if nt:
        ax.text(v + 68, yi, nt, va='center', fontsize=7.2, color='#555555')
ax.set_yticks(y); ax.set_yticklabels(stages, fontsize=8)
ax.set_xlabel('Count'); ax.set_xlim(0, 1050)
ax.spines[['top', 'right']].set_visible(False)
save(fig, 'Fig1_IV_funnel')

# ---------- Figure 2: forest plot with MDES band ----------
print('Figure 2: forest plot with MDES band')
mr = rd('MR_main_results_strandverified_2026-09-15.tsv')
SD = {'Milk': 1100, 'Fat': 35, 'Protein': 30, 'Fat_Percent': 0.35, 'Pro_Percent': 0.22}
rows = []
for r in mr:
    sd = SD.get(r['Trait'])
    b = float(r['IVW_beta'])*sd if sd else float(r['IVW_beta'])
    se = float(r['IVW_se'])*sd if sd else float(r['IVW_se'])
    m80 = float(r['MDES80'])*sd if sd else float(r['MDES80'])
    rows.append((r['Trait'], b, se, float(r['IVW_P']), int(r['n_IV']), m80))
rows.sort(key=lambda x: x[3])
fig, ax = plt.subplots(figsize=(6.8, 5.6))
yy = np.arange(len(rows))[::-1]
for yi, (t, b, se, p, n, m80) in zip(yy, rows):
    c = RED if p < 0.05 else BLUE
    ax.plot([b-1.96*se, b+1.96*se], [yi, yi], color=c, lw=1.4, alpha=0.85)
    ax.plot(b, yi, 's', color=c, ms=4)
    ax.plot([m80, m80], [yi-0.28, yi+0.28], color=GREY, lw=1.0, ls='--')
ax.axvline(0, color='k', lw=0.7)
ax.set_yticks(yy); ax.set_yticklabels([f'{t} (n={n})' for t, b, se, p, n, m80 in rows], fontsize=8)
ax.set_xlabel('IVW estimate (trait-native units; dashed grey = MDES80)')
ax.set_title('IVW estimates of 24 exposures on IndexP60 fertility', fontsize=10)
ax.spines[['top', 'right']].set_visible(False)
save(fig, 'Fig3_forest_MDES')

# ---------- Figure 3: per-IV ratios for the nominal signals ----------
print('Figure 3: per-IV for nominal signals')
iv = rd('IV_table_S8_representative_SNPs_2026-09-15.tsv')
sign = {}
for r in csv.DictReader(open(os.path.join(ROOT, 'allele_strand_audit_table_2026-09-15.tsv'), encoding='utf-8'), delimiter='\t'):
    sign[(r['Trait'], r['signal'])] = int(r['sign'])
NOMINAL = ['Fore_udder_att', 'Front_teat_pla', 'Dairy_form', 'Teat_length']
mr_q = {r['Trait']: r for r in rd('MR_main_results_strandverified_2026-09-15.tsv')}
from scipy.stats import chi2 as _chi2
fig, axes = plt.subplots(1, 4, figsize=(9.6, 3.2), sharey=False)
for ax, t in zip(axes, NOMINAL):
    sub = [r for r in iv if r['Trait'] == t and (t, r['signal']) in sign]
    wald = [(float(r['beta_y'])/float(r['beta_x']), float(r['se_y'])/abs(float(r['beta_x']))) for r in sub]
    wald.sort(key=lambda x: x[0])
    yy = np.arange(len(wald))
    ax.hlines(yy, [w-1.96*s for w, s in wald], [w+1.96*s for w, s in wald], color=BLUE, lw=1.2)
    ax.plot([w for w, s in wald], yy, 'o', color=BLUE, ms=3.5)
    ax.axvline(0, color='k', lw=0.7)
    r = mr_q[t]
    qp = _chi2.sf(float(r['Q']), float(r['Q_df'])) if float(r['Q_df']) > 0 else 1.0
    ax.set_title(f'{t} (n={len(wald)}; Q P={qp:.2f})', fontsize=9)
    ax.tick_params(axis='y', labelsize=6)
    ax.spines[['top', 'right']].set_visible(False)
axes[0].set_ylabel('Wald ratio per IV (95% CI)')
save(fig, 'Fig4_perIV_nominal')

# ---------- Figure 4: power curves + negative-control QQ ----------
print('Figure 4: power curves + negative-control QQ')
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.6, 3.4))
ns = np.array([2000, 2448, 5000, 10000, 20000, 50000, 100000])
alpha = 0.05
z = norm.isf(alpha/2) + norm.isf(0.2)
# simplified power model: MDES proportional to 1/sqrt(N), anchored at 0.029 for N=2448
mdes = 0.029 * np.sqrt(2448/ns)
ax1.plot(ns, mdes, 'o-', color=GREEN, lw=1.5, ms=4)
ax1.axhline(0.01, color=GREY, ls=':', lw=1)
ax1.text(50000, 0.011, 'typical target effect\n(1 pp per point)', fontsize=7.5, color=GREY)
ax1.axvline(2448, color=RED, lw=0.8, ls='--')
ax1.text(2600, 0.05, 'this study\nN=2,448', fontsize=7.5, color=RED)
ax1.set_xscale('log'); ax1.set_xlabel('Outcome GWAS sample size (N)')
ax1.set_ylabel('MDES80 (IndexP60 units per point)')
ax1.set_title('Power to detect causal effects', fontsize=9)
ax1.spines[['top', 'right']].set_visible(False)
# negative-control QQ: read the simulation results

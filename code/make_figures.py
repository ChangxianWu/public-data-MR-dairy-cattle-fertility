# ---------- Figure 5: strand audit ----------
print('Figure 5: strand audit')
aud = list(csv.DictReader(open(os.path.join(ROOT, 'allele_strand_audit_table_2026-09-15.tsv'), encoding='utf-8'), delimiter='\t'))

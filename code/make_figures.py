exp_u = np.linspace(0, 1, 200)
ax2.plot(exp_u, exp_u, color=GREY, lw=1, label='Uniform (calibrated)')
ax2.set_xlabel('Expected quantile'); ax2.set_ylabel('Observed quantile')
ax2.set_title('Pseudo-IV simulation calibration', fontsize=9)
ax2.legend(fontsize=7)
ax2.spines[['top', 'right']].set_visible(False)
